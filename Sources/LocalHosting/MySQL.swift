import Foundation

/// A private MySQL instance with its own data folder, separate from any Homebrew service.
enum MySQL {
    static var isRunning: Bool { runningPid(at: Paths.mysqlPid) != nil }

    static var isInitialized: Bool {
        FileManager.default.fileExists(atPath: Paths.mysqlData.appendingPathComponent("mysql.ibd").path)
    }

    /// The account with every privilege.
    static let adminUser = "root"

    static var rootPassword: String? {
        (try? String(contentsOf: Paths.mysqlRootPassword, encoding: .utf8))?
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private static func writeMyCnf(port: Int) throws {
        try FileManager.default.createDirectory(at: Paths.mysqlRun, withIntermediateDirectories: true)
        try """
        # Generated by Local Hosting.
        [mysqld]
        datadir="\(Paths.mysqlData.path)"
        socket="\(Paths.mysqlSocket.path)"
        pid-file="\(Paths.mysqlPid.path)"
        log-error="\(Paths.mysqlErrorLog.path)"
        port=\(port)
        bind-address=127.0.0.1
        mysqlx=OFF
        character-set-server=utf8mb4
        collation-server=utf8mb4_unicode_ci
        """.write(to: Paths.myCnf, atomically: true, encoding: .utf8)
    }

    private static func writeClientCnf(password: String) throws {
        let escaped = password.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        try """
        [client]
        user=\(adminUser)
        password="\(escaped)"
        socket="\(Paths.mysqlSocket.path)"
        """.write(to: Paths.clientCnf, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: Paths.clientCnf.path)
    }

    static func start(port: Int) async throws {
        guard !isRunning else { return }
        if Paths.mysqlSocket.path.utf8.count > 103 {
            throw ShellError("The MySQL socket path is too long for macOS: \(Paths.mysqlSocket.path)")
        }
        // A Local Hosting MySQL we lost track of (crash, deleted pid file) still holds the port.
        await Leftovers.stop(usingConfig: Paths.myCnf)
        try await Ports.ensureFree(port, for: "MySQL", hint: """
        If it's another MySQL, stop it (for example: brew services stop mysql), \
        or give Local Hosting a different port in Databases.
        """)
        try writeMyCnf(port: port)

        let firstRun = !isInitialized
        if firstRun {
            // --initialize refuses a non-empty data folder; clear any half-finished attempt.
            try? FileManager.default.removeItem(at: Paths.mysqlData)
            try await Shell.check(Paths.mysqld, ["--defaults-file=\(Paths.myCnf.path)", "--initialize-insecure"],
                                  what: "Initializing MySQL")
        }

        let result = await Shell.run(Paths.mysqld, ["--defaults-file=\(Paths.myCnf.path)", "--daemonize"])
        guard result.ok, await waitUntilReady() else {
            throw ShellError("MySQL did not start.\n\(result.output)\n\(tailOfErrorLog())")
        }

        if firstRun || rootPassword == nil {
            let password = Database.generatePassword(length: 20)
            try await Shell.check(Paths.mysql, ["--no-defaults", "--socket=\(Paths.mysqlSocket.path)", "-uroot"],
                                  input: "ALTER USER 'root'@'localhost' IDENTIFIED BY '\(sqlEscape(password))';\n",
                                  what: "Setting the MySQL root password")
            try password.write(to: Paths.mysqlRootPassword, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: Paths.mysqlRootPassword.path)
        }
        try writeClientCnf(password: rootPassword ?? "")
        try? await ensureAdminOverTCP()
    }

    /// Projects that use a custom host name (or 127.0.0.1) connect over TCP, which MySQL
    /// treats as a separate account from the socket's 'localhost'.
    private static func ensureAdminOverTCP() async throws {
        let user = sqlEscape(adminUser)
        let pass = sqlEscape(rootPassword ?? "")
        try await execute("""
        CREATE USER IF NOT EXISTS '\(user)'@'127.0.0.1' IDENTIFIED BY '\(pass)';
        GRANT ALL PRIVILEGES ON *.* TO '\(user)'@'127.0.0.1' WITH GRANT OPTION;
        """)
    }

    private static func waitUntilReady() async -> Bool {
        for _ in 0..<60 {
            // `ping` succeeds once the server answers, even without credentials.
            if await Shell.run(Paths.mysqladmin, ["--no-defaults", "--socket=\(Paths.mysqlSocket.path)", "ping"]).ok {
                return true
            }
            try? await Task.sleep(nanoseconds: 250_000_000)
        }
        return false
    }

    static func stop() async {
        guard let pid = runningPid(at: Paths.mysqlPid) else { return }
        _ = await Shell.run(Paths.mysqladmin, ["--defaults-file=\(Paths.clientCnf.path)", "shutdown"])
        for _ in 0..<100 where kill(pid, 0) == 0 {
            try? await Task.sleep(nanoseconds: 100_000_000)
        }
        if kill(pid, 0) == 0 {
            kill(pid, SIGTERM)
            for _ in 0..<100 where kill(pid, 0) == 0 {
                try? await Task.sleep(nanoseconds: 100_000_000)
            }
        }
    }

    /// Runs SQL as root, fed through stdin so no secrets show up in the process list.
    @discardableResult
    static func execute(_ sql: String) async throws -> String {
        try await Shell.check(Paths.mysql, ["--defaults-file=\(Paths.clientCnf.path)", "--batch", "--skip-column-names"],
                              input: sql, what: "MySQL").stdout
    }

    static func createDatabase(_ db: Database) async throws {
        let user = sqlEscape(db.username)
        let pass = sqlEscape(db.password)
        try await execute("""
        CREATE DATABASE `\(db.name)` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
        CREATE USER IF NOT EXISTS '\(user)'@'localhost' IDENTIFIED BY '\(pass)';
        CREATE USER IF NOT EXISTS '\(user)'@'127.0.0.1' IDENTIFIED BY '\(pass)';
        ALTER USER '\(user)'@'localhost' IDENTIFIED BY '\(pass)';
        ALTER USER '\(user)'@'127.0.0.1' IDENTIFIED BY '\(pass)';
        GRANT ALL PRIVILEGES ON `\(db.name)`.* TO '\(user)'@'localhost', '\(user)'@'127.0.0.1';
        FLUSH PRIVILEGES;
        """)
    }

    static func setPassword(username: String, password: String) async throws {
        let user = sqlEscape(username)
        let pass = sqlEscape(password)
        try await execute("""
        ALTER USER '\(user)'@'localhost' IDENTIFIED BY '\(pass)';
        ALTER USER '\(user)'@'127.0.0.1' IDENTIFIED BY '\(pass)';
        """)
    }

    /// Locked users can't connect; their data is untouched. This is how a single database is
    /// switched off while MySQL keeps serving the others.
    static func setAccess(unlocked: Set<String>, locked: Set<String>) async throws {
        var sql = ""
        for user in unlocked {
            let u = sqlEscape(user)
            sql += "ALTER USER IF EXISTS '\(u)'@'localhost', '\(u)'@'127.0.0.1' ACCOUNT UNLOCK;\n"
        }
        for user in locked {
            let u = sqlEscape(user)
            sql += "ALTER USER IF EXISTS '\(u)'@'localhost', '\(u)'@'127.0.0.1' ACCOUNT LOCK;\n"
        }
        if !sql.isEmpty { try await execute(sql) }
    }

    static func dropDatabase(_ db: Database, dropUser: Bool) async throws {
        var sql = "DROP DATABASE IF EXISTS `\(db.name)`;\n"
        if dropUser {
            let user = sqlEscape(db.username)
            sql += "DROP USER IF EXISTS '\(user)'@'localhost', '\(user)'@'127.0.0.1';\n"
        }
        try await execute(sql)
    }

    // MARK: Browsing

    /// Runs SQL as the admin user and returns every result set. PHP does the talking to MySQL
    /// because it reports NULLs, binary values and errors precisely; the credentials and SQL
    /// travel over stdin, never on a command line.
    static func query(_ sql: String, database: String? = nil, limit: Int = 500) async throws -> QueryResponse {
        let payload: [String: Any] = [
            "user": adminUser, "pass": rootPassword ?? "", "socket": Paths.mysqlSocket.path,
            "db": database ?? "", "limit": limit, "sql": sql,
        ]
        let input = String(decoding: try JSONSerialization.data(withJSONObject: payload), as: UTF8.self)
        let result = await Shell.run(Paths.php, ["-d", "display_errors=stderr", "-d", "memory_limit=512M", "-r", queryScript],
                                     input: input)
        guard let response = try? JSONDecoder().decode(QueryResponse.self, from: Data(result.stdout.utf8)) else {
            throw ShellError("Couldn't read the results from MySQL.\n\(result.output)")
        }
        return response
    }

    private static let queryScript = #"""
    mysqli_report(MYSQLI_REPORT_ERROR | MYSQLI_REPORT_STRICT);
    $in = json_decode(stream_get_contents(STDIN), true);
    $out = ['results' => []];
    try {
        $db = new mysqli('localhost', $in['user'], $in['pass'], '', 0, $in['socket']);
        $db->set_charset('utf8mb4');
        if ($in['db'] !== '') $db->select_db($in['db']);
        $db->multi_query($in['sql']);
        do {
            $result = $db->store_result();
            if ($result instanceof mysqli_result) {
                $rows = [];
                while (count($rows) < $in['limit'] && ($row = $result->fetch_row())) {
                    $rows[] = array_map(function ($v) {
                        if ($v === null) return null;
                        $v = (string) $v;
                        if (mb_check_encoding($v, 'UTF-8')) return $v;
                        return '0x' . strtoupper(bin2hex(substr($v, 0, 32))) . (strlen($v) > 32 ? '…' : '');
                    }, $row);
                }
                $out['results'][] = ['columns' => array_map(fn($f) => $f->name, $result->fetch_fields()),
                                     'rows' => $rows, 'total' => $result->num_rows];
                $result->free();
            } else {
                $out['results'][] = ['affected' => max(0, $db->affected_rows)];
            }
        } while ($db->more_results() && $db->next_result());
    } catch (Throwable $e) {
        $out['error'] = $e->getMessage();
    }
    echo json_encode($out, JSON_INVALID_UTF8_SUBSTITUTE);
    """#

    /// Quotes a database, table or column name.
    static func quoteIdentifier(_ s: String) -> String {
        "`" + s.replacingOccurrences(of: "`", with: "``") + "`"
    }

    static func sqlEscape(_ s: String) -> String {
        s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "'", with: "\\'")
    }

    static func tailOfErrorLog(lines: Int = 8) -> String {
        guard let text = try? String(contentsOf: Paths.mysqlErrorLog, encoding: .utf8) else { return "" }
        return text.split(separator: "\n").suffix(lines).joined(separator: "\n")
    }
}

struct QueryResponse: Decodable {
    var results: [QueryResult]
    var error: String?
}
