import Foundation

/// Runs Homebrew's Nginx with its own generated config (never touches /opt/homebrew/etc/nginx).
/// Like Apache it answers on ports 80 and 443, so only one of the two runs at a time.
enum Nginx {
    static var isRunning: Bool { runningPid(at: Paths.nginxPid) != nil }

    struct Extras {
        /// Certificate for the catch-all that answers unknown hostnames on 443.
        var fallbackCertificate: Certificates.Pair?
        /// Send http:// requests to https://, only once the certificate authority is trusted.
        var redirectToHTTPS = false
        /// Each running server's PHP-FPM socket.
        var phpSockets: [UUID: String] = [:]
    }

    static func writeConfig(servers: [Server], certificates: [UUID: Certificates.Pair], extras: Extras) throws {
        Paths.ensureDirectories()
        try Apache.writeFallbackSite()
        try fastCGIParams.write(to: Paths.nginxFastCGI, atomically: true, encoding: .utf8)

        let tmp = Paths.nginxTmp.path
        var conf = """
        # Generated by Local Hosting. Changes are overwritten whenever a server starts or stops.
        daemon on;
        worker_processes 1;
        pid "\(Paths.nginxPid.path)";
        error_log "\(Paths.nginxErrorLog.path)" warn;

        events {
            worker_connections 512;
        }

        http {
            include "\(Paths.nginxMimeTypes)";
            default_type application/octet-stream;
            access_log "\(Paths.nginxLogs.appendingPathComponent("access.log").path)";
            sendfile on;
            keepalive_timeout 65;
            client_max_body_size 256M;
            fastcgi_read_timeout 120s;
            server_names_hash_bucket_size 128;
            ssl_protocols TLSv1.2 TLSv1.3;
            map $http_upgrade $connection_upgrade {
                default upgrade;
                '' close;
            }
            client_body_temp_path "\(tmp)/body";
            proxy_temp_path "\(tmp)/proxy";
            fastcgi_temp_path "\(tmp)/fastcgi";
            uwsgi_temp_path "\(tmp)/uwsgi";
            scgi_temp_path "\(tmp)/scgi";


        """

        // The first server on each port answers any hostname nothing else claims, with a plain notice.
        conf += fallbackServer(port: 80, certificate: nil)
        if let certificate = extras.fallbackCertificate {
            conf += fallbackServer(port: 443, certificate: certificate)
        }

        for server in servers {
            let certificate = certificates[server.id]
            let redirect = extras.redirectToHTTPS && certificate != nil
            conf += site(server, port: 80, certificate: nil, redirect: redirect, phpSocket: extras.phpSockets[server.id])
            if let certificate {
                conf += site(server, port: 443, certificate: certificate, redirect: false, phpSocket: extras.phpSockets[server.id])
            }
        }
        conf += "}\n"

        try conf.write(to: Paths.nginxConf, atomically: true, encoding: .utf8)
    }

    /// Listening on this Mac only, so other devices on the network can't reach a site.
    private static func listen(port: Int, certificate: Certificates.Pair?, isDefault: Bool = false) -> String {
        let flags = (certificate == nil ? "" : " ssl") + (isDefault ? " default_server" : "")
        return """
            listen 127.0.0.1:\(port)\(flags);
            listen [::1]:\(port)\(flags);

        """
    }

    private static func sslLines(_ certificate: Certificates.Pair?) -> String {
        guard let certificate else { return "" }
        return """
            ssl_certificate "\(certificate.cert.path)";
            ssl_certificate_key "\(certificate.key.path)";

        """
    }

    private static func fallbackServer(port: Int, certificate: Certificates.Pair?) -> String {
        """
            server {
        \(listen(port: port, certificate: certificate, isDefault: true))        server_name _;
                root "\(Paths.fallbackSite.path)";
        \(sslLines(certificate))    }


        """
    }

    private static func site(_ server: Server, port: Int, certificate: Certificates.Pair?, redirect: Bool, phpSocket: String?) -> String {
        var block = """
            # \(server.name)
            server {
        \(listen(port: port, certificate: certificate))        server_name \(server.hostnames.joined(separator: " "));

        """
        if redirect {
            // A temporary (302) redirect, so browsers don't remember it once the server is switched off.
            block += "        return 302 https://$host$request_uri;\n    }\n\n"
            return block
        }
        block += sslLines(certificate)
        if server.siteKind.isApp {
            // Node, Python and Ruby servers run their own process; this just hands requests to it.
            block += """
                    location / {
                        proxy_pass http://127.0.0.1:\(server.port ?? server.siteKind.defaultPort);
                        proxy_http_version 1.1;
                        proxy_read_timeout 300s;
                        proxy_set_header Host $http_host;
                        proxy_set_header X-Forwarded-For $remote_addr;
                        proxy_set_header X-Forwarded-Proto $scheme;
                        proxy_set_header X-Forwarded-Port $server_port;
                        proxy_set_header Upgrade $http_upgrade;
                        proxy_set_header Connection $connection_upgrade;
                    }
                }


            """
            return block
        }
        block += """
                root "\(server.documentRoot)";
                index index.php index.html index.htm;
                autoindex on;

                location / {
                    try_files $uri $uri/ \(phpSocket == nil ? "=404" : "/index.php?$query_string");
                }

                location ~ /\\.ht {
                    deny all;
                }

        """
        if let phpSocket {
            block += """
                    location ~ \\.php(?:/|$) {
                        fastcgi_split_path_info ^(.+?\\.php)(/.*)$;
                        # Not try_files: its internal redirect would drop the path info.
                        if (!-f $document_root$fastcgi_script_name) {
                            return 404;
                        }
                        fastcgi_pass "unix:\(phpSocket)";
                        include "\(Paths.nginxFastCGI.path)";
                        fastcgi_param PATH_INFO $fastcgi_path_info;
                        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
                    }

            """
        }
        block += "    }\n\n"
        return block
    }

    /// What PHP-FPM needs to know about each request.
    private static let fastCGIParams = """
    fastcgi_param QUERY_STRING $query_string;
    fastcgi_param REQUEST_METHOD $request_method;
    fastcgi_param CONTENT_TYPE $content_type;
    fastcgi_param CONTENT_LENGTH $content_length;
    fastcgi_param SCRIPT_NAME $fastcgi_script_name;
    fastcgi_param REQUEST_URI $request_uri;
    fastcgi_param DOCUMENT_URI $document_uri;
    fastcgi_param DOCUMENT_ROOT $document_root;
    fastcgi_param SERVER_PROTOCOL $server_protocol;
    fastcgi_param REQUEST_SCHEME $scheme;
    fastcgi_param HTTPS $https if_not_empty;
    fastcgi_param GATEWAY_INTERFACE CGI/1.1;
    fastcgi_param SERVER_SOFTWARE nginx/$nginx_version;
    fastcgi_param REMOTE_ADDR $remote_addr;
    fastcgi_param REMOTE_PORT $remote_port;
    fastcgi_param SERVER_ADDR $server_addr;
    fastcgi_param SERVER_PORT $server_port;
    fastcgi_param SERVER_NAME $host;
    fastcgi_param REDIRECT_STATUS 200;

    """

    // MARK: Process control

    private static var arguments: [String] {
        ["-e", Paths.nginxErrorLog.path, "-c", Paths.nginxConf.path, "-p", Paths.nginxDir.path]
    }

    static func test() async throws {
        try await Shell.check(Paths.nginx, arguments + ["-t"], what: "Nginx configuration check")
    }

    static func start() async throws {
        try await test()
        await Leftovers.stop(usingConfig: Paths.nginxConf)
        for port in [80, 443] {
            try await Ports.ensureFree(port, for: "Nginx", hint: """
            Quit the other web server (for example MAMP, or macOS's built-in Apache with: sudo apachectl stop), then try again.
            """)
        }
        let result = await Shell.run(Paths.nginx, arguments)
        for _ in 0..<40 where !isRunning {
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        guard isRunning else {
            throw ShellError("Nginx did not start.\n\(result.output)\n\(tailOfErrorLog())")
        }
    }

    /// Reloads the config without dropping connections.
    static func reload() async throws {
        try await test()
        if let pid = runningPid(at: Paths.nginxPid) { kill(pid, SIGHUP) }
    }

    static func stop() async {
        if let pid = runningPid(at: Paths.nginxPid) {
            kill(pid, SIGQUIT)
            for _ in 0..<50 where kill(pid, 0) == 0 {
                try? await Task.sleep(nanoseconds: 100_000_000)
            }
            if kill(pid, 0) == 0 { kill(pid, SIGKILL) }
        }
        await Leftovers.stop(usingConfig: Paths.nginxConf)
        try? FileManager.default.removeItem(at: Paths.nginxPid)
    }

    static func tailOfErrorLog(lines: Int = 8) -> String {
        guard let text = try? String(contentsOf: Paths.nginxErrorLog, encoding: .utf8) else { return "" }
        return text.split(separator: "\n").suffix(lines).joined(separator: "\n")
    }
}
