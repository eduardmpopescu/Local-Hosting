import Foundation

/// Runs Homebrew's Apache with its own generated config (never touches /opt/homebrew/etc/httpd).
enum Apache {
    static var isRunning: Bool { runningPid(at: Paths.apachePid) != nil }

    /// What Apache serves besides the running servers.
    struct Extras {
        /// Certificate for the catch-all that answers unknown hostnames on 443.
        var fallbackCertificate: Certificates.Pair?
        /// Send http:// requests to https://. Only when the certificate authority is trusted,
        /// otherwise the browser would land on a certificate warning.
        var redirectToHTTPS = false
        /// Each running server's PHP-FPM socket.
        var phpSockets: [UUID: String] = [:]
    }

    static func writeConfig(servers: [Server], certificates: [UUID: Certificates.Pair], extras: Extras) throws {
        Paths.ensureDirectories()
        try writeFallbackSite()

        let m = Paths.httpdModules
        let modules = [
            "mpm_prefork", "authz_core", "authz_host", "authn_core", "unixd", "mime", "dir", "alias",
            // Real projects' .htaccess files use these: "Order/Deny from all" and password-protected folders.
            "access_compat", "auth_basic", "authn_file", "authz_user", "authz_groupfile",
            "autoindex", "log_config", "env", "setenvif", "headers", "rewrite", "expires", "deflate",
            "filter", "ssl", "socache_shmcb", "proxy", "proxy_fcgi", "proxy_http",
        ]

        var conf = """
        # Generated by Local Hosting. Changes are overwritten whenever a server starts or stops.
        ServerRoot "\(Paths.httpdRoot)"
        DefaultRuntimeDir "\(Paths.apacheRun.path)"
        PidFile "\(Paths.apachePid.path)"
        ServerName localhost
        Timeout 120

        Listen 0.0.0.0:80
        Listen [::]:80
        Listen 0.0.0.0:443
        Listen [::]:443

        """
        for module in modules {
            conf += "LoadModule \(module)_module \"\(m)/mod_\(module).so\"\n"
        }
        conf += """

        TypesConfig "\(Paths.mimeTypes)"
        DirectoryIndex index.php index.html index.htm
        # PHP-FPM doesn't see this header on its own; frameworks need it for API tokens and basic auth.
        SetEnvIfNoCase ^Authorization$ "(.+)" HTTP_AUTHORIZATION=$1

        ErrorLog "\(Paths.apacheErrorLog.path)"
        LogLevel warn
        LogFormat "%h %l %u %t \\"%r\\" %>s %b \\"%{Referer}i\\" \\"%{User-Agent}i\\"" combined
        CustomLog "\(Paths.apacheLogs.appendingPathComponent("access.log").path)" combined

        SSLProtocol -all +TLSv1.2 +TLSv1.3
        SSLSessionCache "shmcb:\(Paths.apacheRun.path)/ssl_scache(512000)"

        <Directory />
            AllowOverride None
            Require all denied
        </Directory>
        <Files ".ht*">
            Require all denied
        </Files>


        """

        // The first vhost on each port answers any hostname nothing else claims, with a plain notice.
        conf += fallbackVhost(port: 80, certificate: nil)
        if let certificate = extras.fallbackCertificate {
            conf += fallbackVhost(port: 443, certificate: certificate)
        }

        for server in servers {
            let certificate = certificates[server.id]
            let php = extras.phpSockets[server.id]
            conf += vhost(for: server, port: 80, certificate: nil, redirect: extras.redirectToHTTPS && certificate != nil, phpSocket: php)
            if let certificate {
                conf += vhost(for: server, port: 443, certificate: certificate, redirect: false, phpSocket: php)
            }
        }

        try conf.write(to: Paths.httpdConf, atomically: true, encoding: .utf8)
    }

    private static func sslLines(_ certificate: Certificates.Pair?) -> String {
        guard let certificate else { return "" }
        return """
            SSLEngine on
            SSLCertificateFile "\(certificate.cert.path)"
            SSLCertificateKeyFile "\(certificate.key.path)"

        """
    }

    /// A temporary (302) redirect, so browsers don't remember it once the server is switched off
    /// and the domain goes back to the real website.
    private static let httpsRedirect = """
        RewriteEngine On
        RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=302,L]

    """

    private static func fallbackVhost(port: Int, certificate: Certificates.Pair?) -> String {
        """
        <VirtualHost *:\(port)>
            ServerName unknown.invalid
            DocumentRoot "\(Paths.fallbackSite.path)"
            <Directory "\(Paths.fallbackSite.path)">
                Require local
            </Directory>
        \(sslLines(certificate))</VirtualHost>


        """
    }

    private static func vhost(for server: Server, port: Int, certificate: Certificates.Pair?, redirect: Bool, phpSocket: String?) -> String {
        let root = server.documentRoot
        let aliases = server.hostnames.dropFirst().joined(separator: " ")
        var block = """
        # \(server.name)
        <VirtualHost *:\(port)>
            ServerName \(server.hostnames[0])

        """
        if !aliases.isEmpty { block += "    ServerAlias \(aliases)\n" }
        if redirect { block += httpsRedirect }
        if server.siteKind.isApp {
            // Node, Python and Ruby servers run their own process; this just hands requests to it.
            let target = "http://127.0.0.1:\(server.port ?? server.siteKind.defaultPort)/"
            block += """
                ProxyPreserveHost On
                RequestHeader set X-Forwarded-Proto "\(port == 443 ? "https" : "http")"
                RequestHeader set X-Forwarded-Port "\(port)"
                ProxyPass "/" "\(target)" upgrade=websocket
                ProxyPassReverse "/" "\(target)"
                <Location "/">
                    Require local
                </Location>

            """
            block += sslLines(certificate)
            block += "</VirtualHost>\n\n"
            return block
        }
        block += """
            DocumentRoot "\(root)"
            <Directory "\(root)">
                Options Indexes FollowSymLinks
                AllowOverride All
                Require local
            </Directory>
            # <Location> is applied after .htaccess files, so a project's own "Require all granted"
            # can't open the site to other devices on the network. "And" keeps the project's own rules.
            <Location "/">
                AuthMerging And
                Require local
            </Location>

        """
        if let phpSocket {
            block += """
                <FilesMatch "\\.php$">
                    SetHandler "proxy:unix:\(phpSocket)|fcgi://localhost"
                </FilesMatch>

            """
        }
        block += sslLines(certificate)
        block += "</VirtualHost>\n\n"
        return block
    }

    static func writeFallbackSite() throws {
        try """
        <!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width">
        <title>Nothing here</title>
        <body style="font:16px -apple-system,system-ui,sans-serif;max-width:36em;margin:5em auto;padding:0 16px;line-height:1.5">
        <h1 style="font-size:22px">Nothing is served at this address</h1>
        <p>No running server in Local Hosting uses this name. Switch the server on in Local Hosting, then reload this page.</p>
        </body>
        """.write(to: Paths.fallbackSite.appendingPathComponent("index.html"), atomically: true, encoding: .utf8)
    }

    // MARK: Process control

    static func test() async throws {
        try await Shell.check(Paths.httpd, ["-f", Paths.httpdConf.path, "-t"], what: "Apache configuration check")
    }

    static func start() async throws {
        try await test()
        await Leftovers.stop(usingConfig: Paths.httpdConf)
        for port in [80, 443] {
            try await Ports.ensureFree(port, for: "Apache", hint: """
            Quit the other web server (for example MAMP, or macOS's built-in Apache with: sudo apachectl stop), then try again.
            """)
        }
        let result = await Shell.run(Paths.httpd, ["-f", Paths.httpdConf.path, "-k", "start"])
        for _ in 0..<40 where !isRunning {
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        guard isRunning else {
            throw ShellError("Apache did not start.\n\(result.output)\n\(tailOfErrorLog())")
        }
    }

    /// Reloads the config without dropping connections.
    static func reload() async throws {
        try await test()
        try await Shell.check(Paths.httpd, ["-f", Paths.httpdConf.path, "-k", "graceful"], what: "Apache reload")
    }

    static func stop() async {
        guard let pid = runningPid(at: Paths.apachePid) else { return }
        _ = await Shell.run(Paths.httpd, ["-f", Paths.httpdConf.path, "-k", "stop"])
        for _ in 0..<50 where kill(pid, 0) == 0 {
            try? await Task.sleep(nanoseconds: 100_000_000)
        }
        if kill(pid, 0) == 0 { kill(pid, SIGKILL) }
        try? FileManager.default.removeItem(at: Paths.apachePid)
    }

    static func tailOfErrorLog(lines: Int = 8) -> String {
        guard let text = try? String(contentsOf: Paths.apacheErrorLog, encoding: .utf8) else { return "" }
        return text.split(separator: "\n").suffix(lines).joined(separator: "\n")
    }
}
